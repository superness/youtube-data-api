def get_proxy_dict() -> dict:
    url = (
        f"http://{settings.webshare_proxy_username}:{settings.webshare_proxy_password}"
        f"@p.webshare.io:80"
    )
    return {"http": url, "https": url}


def get_random_user_agent() -> str:
    return random.choice(_USER_AGENTS)
